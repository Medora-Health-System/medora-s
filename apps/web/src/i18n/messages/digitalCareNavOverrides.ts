const DIGITAL_CARE_COPY: Record<ProductUiLanguage, Record<string, string>> = {
  en: EN,
  fr: FR,
  es: ES,
};

export function resolveDigitalCareNavOverride(language: string, key: string): string | undefined {
  const lang = language === "fr" || language === "es" ? language : "en";
  return DIGITAL_CARE_COPY[lang][key];
}

export function digitalCareOverlayKeyParity(): string[] {
  const en = Object.keys(EN);
  const missing: string[] = [];
  for (const lang of ["fr", "es"] as const) {
    for (const key of en) {
      if (!DIGITAL_CARE_COPY[lang][key]) missing.push(`${lang}:${key}`);
    }
    for (const key of Object.keys(DIGITAL_CARE_COPY[lang])) {
      if (!EN[key]) missing.push(`en-missing:${key}`);
    }
  }
  return missing;
}
