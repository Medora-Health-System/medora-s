const COPY: Record<ProductUiLanguage, Record<string, string>> = { en: EN, fr: FR, es: ES };

export function resolveFacilityConfigurationOverride(language: string, key: string): string | undefined {
  const lang = language === "fr" || language === "es" ? language : "en";
  return COPY[lang][key];
}

export function facilityConfigurationOverlayKeyParity(): string[] {
  const missing: string[] = [];
  for (const lang of ["fr", "es"] as const) {
    for (const key of Object.keys(EN)) {
      if (!COPY[lang][key]) missing.push(`${lang}:${key}`);
    }
    for (const key of Object.keys(COPY[lang])) {
      if (!EN[key]) missing.push(`en-missing:${key}`);
    }
  }
  return missing;
}
